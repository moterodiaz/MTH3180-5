function write_modal_validation(results,output_dir)
    % Machine-readable metrics plus a self-contained numerical report.
    report = rmfield(results,{'modes','parameters'});
    report.modes = arrayfun(@(m) rmfield(m,{'t','nonlinear','analytical'}),results.modes);
    fid = fopen(fullfile(output_dir,'validation.json'),'w');
    assert(fid~=-1,'Cannot write validation JSON.');
    cleanup = onCleanup(@() fclose(fid));
    fprintf(fid,'%s\n',jsonencode(report,'PrettyPrint',true));
    clear cleanup
    fid = fopen(fullfile(output_dir,'validation.md'),'w');
    assert(fid~=-1,'Cannot write validation report.');
    cleanup = onCleanup(@() fclose(fid));
    fprintf(fid,'# Vibrating-box modal validation\n\nMATLAB %s.\n\n',results.matlab_version);
    fprintf(fid,'Equilibrium `[x; y; theta; vx; vy; vtheta]`:\n\n```text\n');
    fprintf(fid,'%.14g\n',results.equilibrium); fprintf(fid,'```\n\n');
    fields = fieldnames(results.validation);
    for j = 1:numel(fields)
        fprintf(fid,'- `%s`: %.9g\n',fields{j},results.validation.(fields{j}));
    end
    fprintf(fid,'\nMode shapes are columns, ordered by increasing frequency, with `Phi''*M*Phi = I`:\n\n```text\n');
    for j = 1:3, fprintf(fid,'% .12f % .12f % .12f\n',results.mode_shapes(j,:)); end
    fprintf(fid,'```\n\n| Mode | omega rad/(-) | f cycles/(-) | epsilon | RMS error %% | Peak error %% | Leakage %% | RK4 order | Measured cycles |\n');
    fprintf(fid,'|---|---|---|---|---|---|---|---|---|\n');
    for entry = results.modes
        k = entry.mode; m = entry.metrics;
        fprintf(fid,'| %d | %.9f | %.9f | %.8f | %.5f | %.5f | %.5f | %.5f | %d |\n', ...
            k,results.omega(k),results.frequency(k),entry.amplitude,100*m.rms_error, ...
            100*m.peak_error,100*m.leakage,entry.convergence_order,m.measured_cycles);
    end
    fprintf(fid,['\n## Definitions and limits\n\n' ...
        '- RMS error: Frobenius norm of mass-weighted nonlinear-minus-cosine displacement, divided by the mass-weighted cosine displacement norm over the entire 12-period trajectory.\n' ...
        '- Peak error: maximum mass-weighted displacement error divided by epsilon (the mass-normalized mode amplitude).\n' ...
        '- Leakage: maximum Euclidean norm of other-mode phase amplitudes `sqrt(q_j^2 + (qdot_j/omega_j)^2)`, divided by epsilon. Modal coordinates use `Phi\\displacement`.\n' ...
        '- Amplitude search tests true linearized corner displacements from 0.30 down to 0.004. The first candidate with RMS, peak error, and leakage all below 1%% is retained. All trials are in `validation.json`.\n' ...
        '- Frequencies and cycle counts are measured from interpolated positive-going zero crossings of the selected nonlinear modal coordinate. The reported complete-cycle count is floor(duration / measured period).\n' ...
        '- Step convergence compares h, h/2, h/4 at identical times using position and frequency-scaled velocity with mass weighting. Order is log2(error_coarse/error_fine); the fine solution is used for all artifacts.\n' ...
        '- Energy drift is normalized by initial quadratic modal energy, not total energy (which includes an arbitrary potential offset).\n' ...
        '- The equilibrium is a strict local potential minimum: positive eigenvalues of Q and symmetric mass-weighted stiffness. This is stable undamped motion, not asymptotic stability.\n' ...
        '- Nonlinear motion is predominantly, not mathematically exactly, a single mode. Small harmonics, frequency shifts, and leakage remain.\n' ...
        '- Coordinates and time use the assignment''s dimensionless convention (-); orientation is in rad. Frequencies are not labeled Hz.\n\n']);
    for entry = results.modes
        m = entry.metrics;
        fprintf(fid,['Mode %d: coordinate RMS/amplitude errors [x y theta] = [%.6g %.6g %.6g]%%; ' ...
            'relative frequency shift %.6g%%; relative oscillatory-energy drift %.6g; ' ...
            'RK4 medium-to-fine relative difference %.6g; steps [%.9g %.9g %.9g]; ' ...
            'maximum corner peak-to-peak travel %.6g (-).\n\n'], ...
            entry.mode,100*m.coordinate_rms_error,100*m.relative_frequency_error, ...
            m.relative_energy_drift,entry.convergence_relative_error,entry.step_sizes,m.corner_peak_to_peak);
    end
    fprintf(fid,'Selected animation: mode %d, `%s`. Video rendered: %d.\n\n', ...
        results.selected_mode,results.video_file,results.video_rendered);
    fprintf(fid,'Playback speed %.9g simulation-time units per playback second (slow motion). No motion amplification.\n', ...
        results.video_options.playback_speed);
    if isfield(results,'video')
        fprintf(fid,'\nVideo: %d x %d, %.0f fps, %d frames, %.6f s duration, %.9g simulation-time span.\n', ...
            results.video.width,results.video.height,results.video.fps, ...
            results.video.frame_count,results.video.duration,results.video.simulation_duration);
    end
    fprintf(fid,['\nSource attribution: `approximate_jacobian.m` and `multi_newton_solver.m` copied unchanged except attribution headers from ' ...
        '`../MTH3199-Assignment-3`, commit `2c614d9f8d148b162ed373f79ef71a0706bce013`. ' ...
        'No earlier repository was modified. The unavailable video example and Orion reference were not reviewed.\n']);
end
